p.A(340, 130, 220, 34, "head", "接消息与回消息")
p.A(620, 130, 220, 34, "head", "两条消息队列")
p.A(900, 130, 220, 34, "head", "找对会话并分发")
p.A(1180, 130, 220, 34, "head", "想与做")
p.A(1460, 130, 220, 34, "head", "推理与工具调用")

# ① 用户
u1 = p.A(60, 190, 220, 56, "user", "用户输入问题", "（敲回车，读入一行）")
u2 = p.A(60, 1440, 220, 56, "user", "用户看到回答", "（出现下一个提示符）")

# ② 渠道层
c1 = p.A(340, 190, 220, 56, "chan", "读取这一行输入")
c2 = p.A(340, 290, 220, 80, "dec", "是空行，", "或以斜线开头", "的本地命令？")
