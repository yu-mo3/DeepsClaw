c4 = p.A(340, 550, 220, 56, "chan", "推进入站消息队列")
c5 = p.A(340, 650, 220, 66, "chan", "本渠道挂起，", "等待这条消息的回复", "（等不到就不读下一行）")
c6 = p.A(340, 1440, 220, 70, "chan", "把回复打印给用户", "（回答单独走标准输出）", "同时放行下一句提问")
c7 = p.A(40, 660, 260, 56, "stop", "本地命令自己处理完", "（清空历史、看工具清单…）")

# ③ 消息总线
b1 = p.A(620, 430, 220, 66, "bus", "入站消息队列", "（先进先出，来一条排一条）")
b2 = p.A(620, 1240, 220, 66, "bus", "出站消息队列", "（回复在这里排队等发送）")

# ④ 网关
g1 = p.A(900, 430, 220, 66, "gw", "从入站队列取出一条", "（取不到就一直等）")
g2 = p.A(900, 550, 220, 66, "gw", "算出会话身份", "（来源渠道 ＋ 发送者）")
g3 = p.A(900, 660, 220, 80, "dec", "这个会话", "以前来过吗？")
g4 = p.A(900, 800, 220, 74, "gw", "复用这个会话，", "对话历史接着用", "（上下文不丢）")
g5 = p.A(1180, 800, 220, 74, "gw", "新建一个会话，", "从磁盘恢复它的历史", "（丢掉末尾残段）")
g6 = p.A(900, 1340, 220, 66, "gw", "封装成出站消息", "（带上来时的渠道与去处）")
g7 = p.A(900, 1440, 220, 66, "gw", "按“来时的渠道”找出口", "（从哪来，回哪去）")

# ⑤ 智能体循环
a1 = p.A(1180, 520, 220, 80, "ag", "① 进入智能体循环", "拼出系统提示：", "人设＋时间＋工作区＋记忆＋技能")
